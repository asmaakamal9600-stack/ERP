
const PASSWORD_ITERATIONS = 310_000;
const PASSWORD_ALGORITHM = "PBKDF2";
const HASH_ALGORITHM = "SHA-256";

const encoder = new TextEncoder();

function toBase64Url(bytes: Uint8Array): string {
  let binary = "";

  for (const byte of bytes) {
    binary += String.fromCharCode(byte);
  }

  return btoa(binary)
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/g, "");
}

function fromBase64Url(value: string): Uint8Array {
  if (!/^[A-Za-z0-9_-]+$/.test(value)) {
    throw new Error("Invalid encoded value");
  }

  const base64 = value
    .replace(/-/g, "+")
    .replace(/_/g, "/");

  const padded = base64 + "=".repeat((4 - base64.length % 4) % 4);
  const binary = atob(padded);

  return Uint8Array.from(binary, (character) =>
    character.charCodeAt(0)
  );
}

function randomBytes(length: number): Uint8Array {
  if (!Number.isInteger(length) || length < 1 || length > 1024) {
    throw new Error("Invalid random byte length");
  }

  return crypto.getRandomValues(new Uint8Array(length));
}

export function generateSecureToken(bytes = 32): string {
  return toBase64Url(randomBytes(bytes));
}

export function generateVerificationCode(): string {
  // Generate a uniformly distributed six-digit code.
  // Rejection sampling avoids modulo bias.
  const limit = Math.floor(2 ** 32 / 1_000_000) * 1_000_000;
  const buffer = new Uint32Array(1);

  let value: number;

  do {
    crypto.getRandomValues(buffer);
    value = buffer[0];
  } while (value >= limit);

  return String(value % 1_000_000).padStart(6, "0");
}

export function normalizeEmail(email: string): string {
  return email.trim().toLowerCase();
}

export function validateEmail(email: string): boolean {
  if (email.length < 3 || email.length > 254) {
    return false;
  }

  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
}

export function validateUsername(username: string): boolean {
  return /^[A-Za-z0-9_.-]{3,32}$/.test(username);
}

export function validatePassword(password: string): boolean {
  // Require at least 12 characters and reject extremely long inputs.
  return password.length >= 12 && password.length <= 256;
}

export async function hashPassword(
  password: string
): Promise<string> {
  if (!validatePassword(password)) {
    throw new Error("Password does not meet the requirements");
  }

  const salt = randomBytes(16);

  const key = await crypto.subtle.importKey(
    "raw",
    encoder.encode(password),
    PASSWORD_ALGORITHM,
    false,
    ["deriveBits"]
  );

  const derivedBits = await crypto.subtle.deriveBits(
    {
      name: PASSWORD_ALGORITHM,
      hash: HASH_ALGORITHM,
      salt,
      iterations: PASSWORD_ITERATIONS
    },
    key,
    256
  );

  const hash = new Uint8Array(derivedBits);

  return [
    "pbkdf2",
    "sha256",
    String(PASSWORD_ITERATIONS),
    toBase64Url(salt),
    toBase64Url(hash)
  ].join("$");
}

export async function verifyPassword(
  password: string,
  storedHash: string
): Promise<boolean> {
  try {
    if (
      typeof password !== "string" ||
      password.length > 256 ||
      typeof storedHash !== "string" ||
      storedHash.length > 256
    ) {
      return false;
    }

    const parts = storedHash.split("$");

    if (parts.length !== 5) {
      return false;
    }

    const [scheme, digest, iterationsText, saltText, hashText] = parts;

    if (scheme !== "pbkdf2" || digest !== "sha256") {
      return false;
    }

    const iterations = Number(iterationsText);

    // Only accept the parameters generated by this implementation.
    if (
      iterations !== PASSWORD_ITERATIONS ||
      !Number.isSafeInteger(iterations)
    ) {
      return false;
    }

    const salt = fromBase64Url(saltText);
    const expectedHash = fromBase64Url(hashText);

    if (salt.length !== 16 || expectedHash.length !== 32) {
      return false;
    }

    const key = await crypto.subtle.importKey(
      "raw",
      encoder.encode(password),
      PASSWORD_ALGORITHM,
      false,
      ["deriveBits"]
    );

    const derivedBits = await crypto.subtle.deriveBits(
      {
        name: PASSWORD_ALGORITHM,
        hash: HASH_ALGORITHM,
        salt,
        iterations
      },
      key,
      256
    );

    const actualHash = new Uint8Array(derivedBits);

    // Compare every byte rather than stopping at the first mismatch.
    let difference = 0;

    for (let i = 0; i < expectedHash.length; i++) {
      difference |= expectedHash[i] ^ actualHash[i];
    }

    return difference === 0;
  } catch {
    return false;
  }
}

export async function sha256Hex(value: string): Promise<string> {
  const digest = await crypto.subtle.digest(
    HASH_ALGORITHM,
    encoder.encode(value)
  );

  return Array.from(new Uint8Array(digest))
    .map((byte) => byte.toString(16).padStart(2, "0"))
    .join("");
}

export async function hashSessionToken(
  token: string
): Promise<string> {
  if (token.length < 32 || token.length > 512) {
    throw new Error("Invalid session token");
  }

  return sha256Hex(token);
}

export async function hmacSha256(
  secret: string,
  value: string
): Promise<string> {
  if (secret.length < 32) {
    throw new Error("HMAC secret is not configured securely");
  }

  const key = await crypto.subtle.importKey(
    "raw",
    encoder.encode(secret),
    {
      name: "HMAC",
      hash: HASH_ALGORITHM
    },
    false,
    ["sign"]
  );

  const signature = await crypto.subtle.sign(
    "HMAC",
    key,
    encoder.encode(value)
  );

  return toBase64Url(new Uint8Array(signature));
}
